# frozen_string_literal: true

# Generates pgsqlarbiter's parser from PostgreSQL's own grammar.
#
#   ruby grammar/generate.rb PATH/TO/POSTGRES/SOURCES PG_VERSION_TAG
#
# The source directory must contain gram.y, kwlist.h and COPYRIGHT from the
# PostgreSQL tree (see `rake grammar:fetch`). This script:
#
#   1. Reads every production from gram.y and discards the C actions.
#   2. Keeps only the productions reachable from PreparableStmt (SELECT,
#      INSERT, UPDATE, DELETE and MERGE). Nothing is rewritten: the kept
#      productions and the precedence declarations are PostgreSQL's, verbatim.
#   3. Writes grammar/pg_dml.y, a racc grammar whose only action is to build
#      a concrete syntax tree node per production.
#   4. Writes lib/pgsqlarbiter/keywords.rb from kwlist.h.
#   5. Runs racc to produce lib/pgsqlarbiter/parser.rb.
#
# racc must report zero conflicts, exactly as bison does for gram.y
# (`%expect 0`). Anything else means the extraction lost information and the
# script aborts.

require "set"
require "open3"

src_dir = ARGV.fetch(0) { abort "usage: generate.rb SOURCE_DIR PG_VERSION_TAG" }
pg_tag = ARGV.fetch(1) { abort "usage: generate.rb SOURCE_DIR PG_VERSION_TAG" }
root = File.expand_path("..", __dir__)
START = "PreparableStmt"

copyright = File.read(File.join(src_dir, "COPYRIGHT"), encoding: "UTF-8")
abort "COPYRIGHT: unexpected contents" unless copyright.include?("PostgreSQL Global Development Group")

NOTICE = <<~TEXT + copyright.strip + "\n"
  This file is generated by grammar/generate.rb from the PostgreSQL #{pg_tag}
  sources (src/backend/parser/gram.y, src/include/parser/kwlist.h).
  Do not edit it by hand. PostgreSQL's license follows.

TEXT
notice_comment = NOTICE.lines.map { |l| "# #{l}".rstrip }.join("\n")

# ---------------------------------------------------------------- gram.y

src = File.read(File.join(src_dir, "gram.y"), encoding: "UTF-8")
decl, rules_src, = src.split(/^%%\s*$/)
abort "gram.y: could not find the rules section" unless rules_src

abort "gram.y no longer declares %expect 0" unless decl =~ /^%expect\s+0\s*$/

# Precedence declarations, lowest first as in yacc. A declaration may continue
# on following indented lines.
prec = []
decl.gsub(%r{/\*.*?\*/}m, "").gsub(/\n[ \t]+(?=\S)/, " ").each_line do |l|
  prec << [$1, $2.split] if l =~ /^%(left|right|nonassoc)\s+(.*)$/
end
abort "gram.y: no precedence declarations found" if prec.empty?

# Tokenize the rules section, dropping comments and C actions.
toks = []
action_before = Set.new # indexes of tokens that directly follow an action
i = 0
n = rules_src.length
skip_comment = lambda do
  if rules_src[i, 2] == "/*"
    i = rules_src.index("*/", i) + 2
    true
  elsif rules_src[i, 2] == "//"
    i = rules_src.index("\n", i)
    true
  else
    false
  end
end
while i < n
  c = rules_src[i]
  if c =~ /\s/
    i += 1
  elsif skip_comment.call
    next
  elsif c == "{"
    depth = 0
    loop do
      next if skip_comment.call
      ch = rules_src[i]
      if ch == '"' || ch == "'"
        i += 1
        i += (rules_src[i] == "\\" ? 2 : 1) until rules_src[i] == ch
      elsif ch == "{"
        depth += 1
      elsif ch == "}"
        depth -= 1
      end
      i += 1
      break if depth.zero?
    end
    action_before << toks.length
  elsif c == "'"
    j = rules_src.index("'", i + 1)
    toks << rules_src[i..j]
    i = j + 1
  elsif (m = rules_src[i..].match(/\A%?[A-Za-z_][A-Za-z0-9_]*/))
    toks << m[0]
    i += m[0].length
  elsif ":|;".include?(c)
    toks << c
    i += 1
  else
    abort "gram.y: unexpected #{c.inspect} near #{rules_src[i, 40].inspect}"
  end
end

rules = {} # lhs => [[symbols, %prec token or nil]]
order = []
pos = 0
while pos < toks.length
  lhs = toks[pos]
  abort "gram.y: expected ':' after #{lhs}" unless toks[pos + 1] == ":"
  pos += 2
  alts = []
  cur = []
  pr = nil
  loop do
    t = toks[pos]
    # An action followed by another symbol is a mid-rule action, which changes
    # the grammar. gram.y has none; refuse to guess if that ever changes.
    if action_before.include?(pos) && !["|", ";", "%prec"].include?(t)
      abort "gram.y: mid-rule action in #{lhs}; the extractor cannot represent it"
    end
    case t
    when "|", ";"
      alts << [cur, pr]
      cur = []
      pr = nil
      pos += 1
      break if t == ";"
    when "%prec"
      pr = toks[pos + 1]
      pos += 2
    when "%empty"
      pos += 1
    when nil
      abort "gram.y: unterminated rule #{lhs}"
    else
      cur << t
      pos += 1
    end
  end
  order << lhs unless rules.key?(lhs)
  (rules[lhs] ||= []).concat(alts)
end
abort "gram.y: #{START} not found" unless rules.key?(START)

reach = Set.new
work = [START]
until work.empty?
  s = work.pop
  next if reach.include?(s) || !rules.key?(s)
  reach << s
  rules[s].each { |syms, _| syms.each { |x| work << x if rules.key?(x) } }
end
kept = order.select { |l| reach.include?(l) }

grammar_path = File.join(root, "grammar", "pg_dml.y")
File.open(grammar_path, "w") do |f|
  f.puts notice_comment
  f.puts
  f.puts "class Pgsqlarbiter::Parser"
  f.puts "  prechigh"
  prec.reverse_each { |assoc, syms| f.puts "    #{assoc} #{syms.join(" ")}" }
  f.puts "  preclow"
  f.puts "  expect 0"
  f.puts "  start #{START}"
  f.puts "rule"
  kept.each do |l|
    alts = rules[l].map do |syms, pr|
      "#{syms.join(" ")}#{" = #{pr}" if pr} { result = Node.new(:#{l}, val) }".strip
    end
    f.puts "  #{l}: #{alts.join("\n    | ")} ;"
  end
  f.puts "end"
  f.puts
  f.puts "---- header"
  f.puts notice_comment
  f.puts
  f.puts "---- inner"
  f.puts <<~'RUBY'.gsub(/^(?=.)/, "  ")
    # Parse an array of {Token}s into a concrete syntax tree.
    #
    def parse(tokens)
      @tokens = tokens
      @index = -1
      _racc_do_parse_rb(_racc_setup, false)
    rescue Pgsqlarbiter::RaccRuntime::Racc::ParseError => e
      raise Pgsqlarbiter::ParseError, e.message
    end

    def next_token
      token = @tokens[@index += 1]
      token ? [token.type, token] : [false, nil]
    end

    def on_error(_token_id, token, _value_stack)
      if token
        raise Pgsqlarbiter::ParseError, "syntax error at or near #{token.value.inspect} at position #{token.position}"
      end
      raise Pgsqlarbiter::ParseError, "syntax error at end of input"
    end
  RUBY
end

# ---------------------------------------------------------------- kwlist.h

keywords = []
File.foreach(File.join(src_dir, "kwlist.h")) do |l|
  keywords << [$1, $2] if l =~ /^PG_KEYWORD\("(\w+)",\s*(\w+),\s*\w+,\s*\w+\)/
end
abort "kwlist.h: no keywords found" if keywords.size < 400

File.open(File.join(root, "lib", "pgsqlarbiter", "keywords.rb"), "w") do |f|
  f.puts "# frozen_string_literal: true"
  f.puts
  f.puts notice_comment
  f.puts
  f.puts "module Pgsqlarbiter"
  f.puts "  # PostgreSQL's keyword list: lower-case keyword text to grammar terminal."
  f.puts "  module Keywords"
  f.puts "    POSTGRESQL_VERSION = #{pg_tag.inspect}"
  f.puts
  f.puts "    TOKENS = {"
  keywords.each { |text, token| f.puts "      #{text.inspect} => :#{token}," }
  f.puts "    }.freeze"
  f.puts "  end"
  f.puts "end"
end

# ---------------------------------------------------------------- racc

parser_path = File.join(root, "lib", "pgsqlarbiter", "parser.rb")
out, status = Open3.capture2e("racc", "--embedded", "--frozen", "-o", parser_path, grammar_path)
abort "racc failed:\n#{out}" unless status.success?
abort "racc reported problems; PostgreSQL's grammar has none:\n#{out}" unless out.strip.empty?

# racc --embedded copies its runtime into the output so the parser needs no gem
# at run time. As generated, that copy installs itself as the global ::Racc
# (standing in for the real gem for the whole process if it loads first) and
# tries to load racc's optional C extension. Rewrite it into a private,
# pure-Ruby copy under Pgsqlarbiter::RaccRuntime. Every rewrite must match
# exactly as often as expected, so a racc release that changes its template
# fails here, loudly, instead of silently producing something else.
code = File.read(parser_path, encoding: "UTF-8")
rewrite = lambda do |what, pattern, count = 1, &replacement|
  found = code.scan(pattern).length
  abort "racc output changed (#{what}): expected #{count} match(es), found #{found}" unless found == count
  code = code.gsub(pattern, &replacement)
end

rewrite.call("runtime wrapper start", <<~'OLD') { <<~'NEW' }
  unless $".find {|p| p.end_with?('/racc/parser.rb')}
  $".push "#{__dir__}/racc/parser.rb"
  self.class.module_eval(<<'...end racc/parser.rb/module_eval...', 'racc/parser.rb', 1)
OLD
  module Pgsqlarbiter
    # A private, pure-Ruby copy of racc's parser runtime. It is deliberately not
    # the global ::Racc, so it neither affects nor depends on a racc gem that
    # the host application may load.
    module RaccRuntime; end
  end
  Pgsqlarbiter::RaccRuntime.module_eval(<<'...end racc/parser.rb/module_eval...', 'racc/parser.rb', 1)
NEW
rewrite.call("runtime wrapper end", <<~'OLD') { <<~'NEW' }
  ...end racc/parser.rb/module_eval...
  end
  ###### racc/parser.rb end
OLD
  ...end racc/parser.rb/module_eval...
  ###### racc/parser.rb end
NEW
rewrite.call("info wrapper",
  %r{unless \$"\.find \{\|p\| p\.end_with\?\('/racc/info\.rb'\)\}\n\$"\.push "\#\{__dir__\}/racc/info\.rb"\n\n(module Racc\n.*?\nend\n)\nend\n}m) { $1 }
rewrite.call("global ParseError alias", <<~'OLD') { "" }
  unless defined?(::ParseError)
    ParseError = Racc::ParseError # :nodoc:
  end
OLD
rewrite.call("C extension loader",
  /^    begin\n      if Object\.const_defined\?\(:RUBY_ENGINE\).*?^    rescue LoadError\n(.*?)^    end\n/m) { $1 }
rewrite.call("absolute Racc references", /(?<![A-Za-z])::Racc::/, 2) { "Racc::" }
rewrite.call("parser superclass", "class Parser < Racc::Parser") { "class Parser < RaccRuntime::Racc::Parser" }
abort "racc output still refers to the C extension" if code.include?("racc/cparse") || code.include?("_racc_do_parse_c")
File.write(parser_path, code)

total = rules.values.sum(&:length)
kept_n = kept.sum { |l| rules[l].length }
puts "PostgreSQL #{pg_tag}: kept #{kept.size}/#{rules.size} nonterminals, #{kept_n}/#{total} productions"
puts "wrote #{grammar_path}"
puts "wrote #{parser_path} (#{File.size(parser_path) / 1024} KB)"
